// Captions are built with textContent, so nothing in them is interpreted as HTML.
async function showCaption(page, f, s) {
  await page.evaluate(([css, k, t, x, src]) => {
    if (!document.getElementById('oc-css')) { const st = document.createElement('style'); st.id = 'oc-css'; st.textContent = css; document.head.append(st); }
    let c = document.getElementById('oc-cap'); if (!c) { c = document.createElement('div'); c.id = 'oc-cap'; c.setAttribute('aria-hidden', 'true'); document.body.append(c); }
    c.classList.remove('on');
    setTimeout(() => {
      c.replaceChildren();
      const add = (tag, text, cls) => { const e = document.createElement(tag); e.textContent = text; if (cls) e.className = cls; c.append(e); };
      add('b', src, 'src'); add('i', k); add('h2', t); if (x) add('p', x);
      c.classList.add('on');
    }, 350);
  }, [capCss(f), s.kicker, s.title, s.text, COMPOSITION.sample_label]);
}

