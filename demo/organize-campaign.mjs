// Restrained transitions: a short fade from and to the brand aubergine around each piece.
function faded(src, dst, len) {
  const c = `0x${B.aubergine.slice(1)}`;
  ff(['-i', src, '-vf', `fade=t=in:st=0:d=0.3:color=${c},fade=t=out:st=${(len - 0.3).toFixed(2)}:d=0.3:color=${c}`, '-r', '30', '-c:v', 'libx264', '-crf', '17', '-pix_fmt', 'yuv420p', '-an', dst]);
  return dst;
}

async function cardClip(browser, key, fname, f, s) {
  const id = `oc-${key}-${fname}-${s.id}`;
  const take = await record(browser, id, async (p) => { await p.setContent(cardHtml(f, s)); await p.waitForTimeout((s.duration + 0.8) * 1000); }, null, { width: f.width, height: f.height });
  // Playwright can emit few frames for a static page: hold the last frame if the take came out short.
  const exact = resolve(RAW, `${id}-c.mp4`);
  ff(['-ss', '0.4', '-i', take, '-vf', `tpad=stop_mode=clone:stop_duration=${s.duration}`, '-t', String(s.duration), '-r', '30', '-c:v', 'libx264', '-crf', '17', '-pix_fmt', 'yuv420p', '-an', exact]);
  return faded(exact, resolve(RAW, `${id}-f.mp4`), s.duration);
}

// Check the real downloaded team pack: the group's people are in it, the private contact data is not.
function inspectPack(path) {
  const listing = execFileSync('python', ['-I', '-c', `import sys, zipfile, json
z = zipfile.ZipFile(sys.argv[1])
print(json.dumps({n: z.read(n).decode('utf-8', 'replace') for n in z.namelist()}))`, path], { encoding: 'utf8', maxBuffer: 64 << 20 });
  const files = JSON.parse(listing), all = Object.values(files).join('\n');
  const privateText = [D.note, D.follow_up, D.context, D.handoff_note];
  const leaked = privateText.filter(t => all.includes(t));
  const members = D.group_members.map(i => `${person(i).given} ${person(i).family}`);
  const missing = members.filter(m => !all.includes(m));
  if (leaked.length || missing.length) throw new Error(`team pack check failed: leaked ${JSON.stringify(leaked)}, missing ${JSON.stringify(missing)}`);
  return { files: Object.keys(files).sort(), members_present: members, private_contact_text_absent: privateText };
}

// The demo steps, mapped onto the reusable steps in contacts.mjs / groups.mjs.
function stepRunner(evidence) {
  const top = (p, sel) => p.evaluate((s) => { const el = document.querySelector(s); el.scrollIntoView({ block: 'start' }); window.scrollBy(0, -20); }, sel);
  const given = (i) => person(i).given;
  return {
    guide: (p) => top(p, '#guide'),
    guideSteps: (p) => top(p, '#guide .guide-steps'),
    // Back to the top of the page, where the guide sits above every view.
    guideDone: async (p) => {
      await p.evaluate(() => window.scrollTo(0, 0)); await top(p, '#guide .guide-steps');
      const done = await p.locator('#guide .guide-steps li.done').count();
      evidence.guide_steps_done = done;
      if (done !== 7) throw new Error(`guide shows ${done}/7 steps done`);
    },
    importAndTag: (p) => contactSteps.importAndTag(p, { context: D.context, ids: D.import.map(i => person(i).orcid) }),
    saveAsContact: async (p) => {
      await p.evaluate((id) => { window.scrollTo(0, 0); location.hash = `contacts?save=${id}`; }, person(D.handoff).orcid);
      await contactSteps.saveAsContact(p, { context: D.context, met: isoDay(0), note: D.handoff_note, hold: 2500 });
      await p.waitForTimeout(1500);
      await contactSteps.showCard(p, { given: given(D.handoff) });
    },
    showCard: (p) => contactSteps.showCard(p, { given: given(D.note_for) }),
    note: (p) => contactSteps.addNote(p, { given: given(D.note_for), text: D.note }),
    followUp: (p) => contactSteps.addFollowUp(p, { given: given(D.note_for), title: D.follow_up, due: isoDay(D.follow_up_due_in_days) }),
    openFollowUps: (p) => contactSteps.showOpenFollowUps(p),
    createGroup: (p) => groupSteps.createGroup(p, { name: D.group, members: D.group_members.map(given) }),
    roster: (p) => top(p, '#group-panel'),
    selectOutputs: (p, a) => groupSteps.selectOutputs(p, { count: a.count || 1 }),
    teamPack: async (p) => {
      const pack = await groupSteps.downloadTeamPack(p);
      evidence.team_pack = { file: pack.name, ...inspectPack(pack.path) };
    },
  };
}

// One continuous take for a run of consecutive network segments, in a fresh browser profile.
async function networkClip(browser, base, key, fname, f, segs) {
  const id = `oc-${key}-${fname}-network`;
  const marks = [], evidence = { blocked_external_requests: [] };
  let end = 0;
  const steps = stepRunner(evidence);
  const isolate = async (ctx) => {
    await serveSyntheticOrcid(ctx);
    await ctx.route(url => !url.href.startsWith(base) && !url.href.startsWith('https://pub.orcid.org/'), route => {
      evidence.blocked_external_requests.push(route.request().url()); return route.abort();
    });
  };
  const take = await record(browser, id, async (p, at) => {
    p.setDefaultTimeout(30000);
    p.on('dialog', d => { evidence.unexpected_dialog = d.message(); d.dismiss(); });
    await p.goto(`${base}network/#contacts`);
    await p.locator('#navigation a[aria-current="page"]').waitFor({ timeout: 180000 });
    await p.addStyleTag({ content: 'html{scroll-behavior:auto}' });
    await p.waitForTimeout(2500); // warm-up, trimmed away
    let due = at();
    for (const s of segs) {
      while (at() < due) await p.waitForTimeout(5);
      marks.push({ id: s.id, t: at() });
      await showCaption(p, f, s);
      for (const a of s.actions || []) {
        if (a.wait) await p.waitForTimeout(a.wait * 1000);
        else if (steps[a.step]) await steps[a.step](p, a);
        else throw new Error(`unknown step ${JSON.stringify(a)}`);
      }
      due = marks.at(-1).t + s.duration;
      const slack = due - at();
      marks.at(-1).slack = +slack.toFixed(2);
      if (slack < 0.3) throw new Error(`${key}/${fname}: segment "${s.id}" needs ${(s.duration - slack + 0.3).toFixed(1)} s, planned ${s.duration} s`);
    }
    while (at() < due + 0.5) await p.waitForTimeout(20);
    end = at();
  }, isolate, { width: f.width, height: f.height });
  if (evidence.unexpected_dialog) throw new Error(`unexpected dialog: ${evidence.unexpected_dialog}`);
  // Playwright's video can start a little after the clock used for the marks (more often for large frames).
  // Measure that start lag from the take itself and cut on the video's own timeline.
  const lag = Math.max(0, end - duration(take));
  const len = segs.reduce((a, s) => a + s.duration, 0), t0 = marks[0].t - lag;
  if (t0 < 0 || t0 + len > duration(take)) throw new Error(`${id}: take too short to cut ${len} s at ${t0.toFixed(2)} s`);
  const exact = cut(take, t0, t0 + len, resolve(RAW, `${id}-c.mp4`));
  return {
    file: faded(exact, resolve(RAW, `${id}-f.mp4`), len), evidence,
    take: { id, video_start_lag_seconds: +lag.toFixed(2), continuous_segments: segs.map(s => s.id), segment_slack_seconds: Object.fromEntries(marks.map(m => [m.id, m.slack])) },
  };
}

function withAudio(src, dst, total) {
  const narration = flag('narration'), music = flag('music');
  if (!narration && !music) return null;
  const inputs = ['-i', src], parts = [], labels = [];
  if (narration) { inputs.push('-i', narration); parts.push(`[1:a]apad,atrim=0:${total}[n]`); labels.push('[n]'); }
  if (music) {
    inputs.push('-stream_loop', '-1', '-i', music);
    parts.push(`[${labels.length + 1}:a]volume=${COMPOSITION.audio.music_gain_db}dB,atrim=0:${total},afade=t=out:st=${total - 2}:d=2[m]`); labels.push('[m]');
  }
  parts.push(`${labels.join('')}amix=inputs=${labels.length}:normalize=0[a]`);
  ff([...inputs, '-filter_complex', parts.join(';'), '-map', '0:v', '-map', '[a]', '-c:v', 'copy', '-c:a', 'aac', '-b:a', '160k', '-t', String(total), '-movflags', '+faststart', dst]);
  return dst;
}

