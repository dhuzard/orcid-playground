// ---------- Caption drafts: derived from the composition only, so they are deterministic. ----------

// A cue starts once the on-screen caption has faded in and ends just before the next segment.
export function cues(variant) {
  let t = 0;
  return COMPOSITION.variants[variant].segments.map((s) => {
    const cue = { id: s.id, start: t + 0.4, end: t + s.duration - 0.1, lines: [s.title, s.text].filter(Boolean) };
    t += s.duration;
    return cue;
  });
}
const stamp = (sec, sep) => {
  const ms = Math.round(sec * 1000), h = Math.floor(ms / 3600000), m = Math.floor(ms / 60000) % 60, s = Math.floor(ms / 1000) % 60;
  return `${[h, m, s].map(x => String(x).padStart(2, '0')).join(':')}${sep}${String(ms % 1000).padStart(3, '0')}`;
};
const vtt = (v) => ['WEBVTT', '', `NOTE ${BANNER}`, '', `NOTE Captions for ${COMPOSITION.variants[v].title}. The video is silent; these repeat the on-screen captions.`, '',
  ...cues(v).flatMap(c => [c.id, `${stamp(c.start, '.')} --> ${stamp(c.end, '.')}`, ...c.lines, ''])].join('\n');
const srt = (v) => cues(v).flatMap((c, i) => [String(i + 1), `${stamp(c.start, ',')} --> ${stamp(c.end, ',')}`, ...c.lines, '']).join('\n');
const clock = (sec) => `${Math.floor(sec / 60)}:${String(sec % 60).padStart(2, '0')}`;

function transcript() {
  const out = [`# Explore & Play video — transcript (DRAFT)`, '', `> **${BANNER}**`, '> Do not post, upload or link this video or text until #44 has an outcome that allows promotion and Release B in',
    '> `communications/release-checklist.md` is signed by the owner after checking the hosted site.', '',
    'Generated by `node demo/play-campaign.mjs --text-only` from `demo/play-campaign.json`; edit the JSON, not this file.', '',
    '**Audio:** none. The videos are silent with burned-in captions. No narration or music has been recorded or licensed;',
    'the renderer can mix one in only if a file is passed explicitly (`--narration=`, `--music=`).', '',
    `**Data on screen:** ${COMPOSITION.data_source}`, ''];
  for (const [key, v] of Object.entries(COMPOSITION.variants)) {
    const total = v.segments.reduce((a, s) => a + s.duration, 0);
    out.push(`## ${v.title} (\`${key}\`, ${total} s, ${v.formats.join(' + ')})`, '', '| Time | Segment | On screen | Caption |', '|---|---|---|---|');
    let t = 0;
    for (const s of v.segments) {
      const text = [s.kicker, `**${s.title}**`, s.text].filter(Boolean).join(' · ').replace(/\|/g, '\\|');
      out.push(`| ${clock(t)}–${clock(t + s.duration)} | \`${s.id}\` | ${s.screen} | ${text} |`);
      t += s.duration;
    }
    out.push('');
  }
  out.push('Every closing card also shows the exact disclaimer and trademark line from `config/brand.json`.', '');
  return out.join('\n');
}

export function writeDrafts() {
  mkdirSync(DRAFTS, { recursive: true });
  for (const v of Object.keys(COMPOSITION.variants)) {
    writeFileSync(resolve(DRAFTS, `${v}-DRAFT.vtt`), vtt(v));
    writeFileSync(resolve(DRAFTS, `${v}-DRAFT.srt`), srt(v));
  }
  writeFileSync(resolve(DRAFTS, 'transcript-DRAFT.md'), transcript());
}

writeDrafts();
if (textOnly) { console.log('wrote caption drafts to', DRAFTS); process.exit(0); }

