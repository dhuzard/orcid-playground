// Explore & Play launch video (#58): a 42 s social cut and a ~2 min walkthrough, from the web app UI only.
//
//   node demo/play-campaign.mjs site                 # render videos into demo/out/ and refresh the caption drafts
//   node demo/play-campaign.mjs --text-only          # only (re)write the caption/transcript drafts, no browser
//   node demo/play-campaign.mjs site --variant=play-campaign
//   node demo/play-campaign.mjs site --music=<file> --narration=<file>   # optional, off by default
//
// DRAFT — NOT APPROVED FOR PUBLICATION. Blocked by #44 and communications/release-checklist.md (Release B).
//
// The composition (segments, durations, caption text, brand colours, caption sizes) lives in
// demo/play-campaign.json so tests/test_play_campaign.py can check it against the claim rules.
// Screens come from one continuous take per variant and format: each segment starts at a mark and the take
// waits until exactly `duration` seconds later, so segment boundaries land on the planned times.
// The data is the stored demonstration profile served with the built site; no ORCID API call is made.
// The Studio → network bridge and any first-run guide are hidden so the video only shows merged Explore & Play UI.
// No narration or music asset is included; the default render is silent with burned-in captions.
