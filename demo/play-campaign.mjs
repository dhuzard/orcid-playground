// Restrained transitions: a short fade from and to the brand aubergine around each piece.
function faded(src, dst, len) {
  const c = `0x${B.aubergine.slice(1)}`;
  ff(['-i', src, '-vf', `fade=t=in:st=0:d=0.3:color=${c},fade=t=out:st=${(len - 0.3).toFixed(2)}:d=0.3:color=${c}`, '-r', '30', '-c:v', 'libx264', '-crf', '17', '-pix_fmt', 'yuv420p', '-an', dst]);
  return dst;
}

async function cardClip(browser, key, fname, f, s) {
  const id = `${key}-${fname}-${s.id}`;
  const take = await record(browser, id, async (p) => { await p.setContent(cardHtml(f, s)); await p.waitForTimeout((s.duration + 0.8) * 1000); }, null, { width: f.width, height: f.height });
  // Playwright can emit few frames for a static page: hold the last frame if the take came out short.
  const exact = resolve(RAW, `${id}-c.mp4`);
  ff(['-ss', '0.4', '-i', take, '-vf', `tpad=stop_mode=clone:stop_duration=${s.duration}`, '-t', String(s.duration), '-r', '30', '-c:v', 'libx264', '-crf', '17', '-pix_fmt', 'yuv420p', '-an', exact]);
  return faded(exact, resolve(RAW, `${id}-f.mp4`), s.duration);
}

async function runAction(p, a) {
  if (a.wait) return p.waitForTimeout(a.wait * 1000);
  if (a.tab) {
    await p.click(`[data-tab="${a.tab}"]`);
    await p.evaluate(() => document.querySelector('#tabs').scrollIntoView({ behavior: 'smooth', block: 'start' }));
    return p.waitForTimeout(500);
  }
  if (a.scrollTo) { await p.evaluate((sel) => document.querySelector(sel).scrollIntoView({ behavior: 'smooth', block: 'start' }), a.scrollTo); return p.waitForTimeout(700); }
  // A real button on the page; the Fortune tab's "Another one" draws with seed 1 first, so the title is reproducible.
  if (a.click) { await p.click(a.click); return p.waitForTimeout(900); }
  if (a.scroll) { await p.mouse.wheel(0, a.scroll); return p.waitForTimeout(400); }
  throw new Error(`unknown action ${JSON.stringify(a)}`);
}

// One continuous Studio take for a run of consecutive studio segments.
async function studioClip(browser, base, key, fname, f, segs) {
  const id = `${key}-${fname}-studio`;
  const marks = [];
  const take = await record(browser, id, async (p, at) => {
    await p.goto(base);
    await p.addStyleTag({ content: `${COMPOSITION.hide_selectors.join(',')}{display:none!important}html{scroll-behavior:auto}
      .art img{height:${f.art_px}px!important;width:auto!important;max-width:100%}` }); // art sits above the caption box
    // Warm-up (trimmed away): load the stored profile with the page's own button, then return to the chip.
    await p.click('[data-sample]');
    await p.waitForSelector('#tabs button', { timeout: 180000 });
    await p.waitForTimeout(1500);
    await p.evaluate((sel) => document.querySelector(sel).scrollIntoView({ block: 'center' }), COMPOSITION.preroll_scroll);
    await p.waitForTimeout(1200);
    let due = at();
    for (const s of segs) {
      while (at() < due) await p.waitForTimeout(5);
      marks.push({ id: s.id, t: at() });
      await showCaption(p, f, s);
      for (const a of s.actions || []) await runAction(p, a);
      due = marks.at(-1).t + s.duration;
    }
    while (at() < due + 0.5) await p.waitForTimeout(20);
  }, null, { width: f.width, height: f.height });
  const t0 = marks[0].t, len = segs.reduce((a, s) => a + s.duration, 0);
  const exact = cut(take, t0, t0 + len, resolve(RAW, `${id}-c.mp4`));
  return { file: faded(exact, resolve(RAW, `${id}-f.mp4`), len), drift: marks.map((m, i) => ({ id: m.id, offset: +(m.t - t0 - segs.slice(0, i).reduce((a, s) => a + s.duration, 0)).toFixed(3) })) };
}

function withAudio(src, dst, total) {
  const narration = flag('narration'), music = flag('music');
  if (!narration && !music) return null;
  const inputs = ['-i', src], parts = [], labels = [];
  if (narration) { inputs.push('-i', narration); parts.push(`[${inputs.length / 2 - 1}:a]apad,atrim=0:${total}[n]`); labels.push('[n]'); }
  if (music) {
    inputs.push('-stream_loop', '-1', '-i', music);
    const idx = inputs.filter(x => x === '-i').length - 1;
    parts.push(`[${idx}:a]volume=${COMPOSITION.audio.music_gain_db}dB,atrim=0:${total},afade=t=out:st=${total - 2}:d=2[m]`); labels.push('[m]');
  }
  parts.push(`${labels.join('')}amix=inputs=${labels.length}:normalize=0[a]`);
  ff([...inputs, '-filter_complex', parts.join(';'), '-map', '0:v', '-map', '[a]', '-c:v', 'copy', '-c:a', 'aac', '-b:a', '160k', '-t', String(total), '-movflags', '+faststart', dst]);
  return dst;
}

